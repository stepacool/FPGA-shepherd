"""Generated backend project: board allowlist, apio.ini, and the staged source tree.

apio has no source-list option: it globs every **/*.v and **/*.sv under the project dir
and sorts them by name. So each run stages an isolated project under .shepherd/build/
with one index-prefixed symlink per source, which keeps the shepherd.toml order.
"""

from __future__ import annotations

from pathlib import Path

from shepherd.backend.base import Staging
from shepherd.config import STATE_DIR, ProjectConfig
from shepherd.errors import UnknownBoard

# Shepherd board name → apio board id. Not a board registry: just a friendly-name map.
BOARDS = {
    "tangnano9k": "sipeed-tang-nano-9k",
}

# The apio board definition programs flash (-f) by default; Shepherd defaults to SRAM.
PROGRAMMER_SRAM = "openFPGALoader --force-terminal-mode -b tangnano9k ${BIN_FILE}"
PROGRAMMER_FLASH = "openFPGALoader --force-terminal-mode --verify -b tangnano9k -f ${BIN_FILE}"

BUILD_SUBDIR = "build"
CACHE_DIR = "_build"
ENV = "default"
CONSTRAINTS_NAME = "constraints.cst"


def resolve_board(name: str) -> str:
    try:
        return BOARDS[name]
    except KeyError:
        supported = ", ".join(sorted(BOARDS))
        raise UnknownBoard(
            f"board '{name}' is not supported in this version",
            hint=f"supported boards: {supported}",
        ) from None


def staging_dir(root: Path) -> Path:
    return root / STATE_DIR / BUILD_SUBDIR


def bitstream_path(stage_dir: Path) -> Path:
    return stage_dir / CACHE_DIR / ENV / "hardware.fs"


def apio_ini(board_id: str, top: str, constraints: bool, flash: bool) -> str:
    lines = [
        "; Generated by Shepherd from shepherd.toml on every run. Do not edit.",
        "",
        f"[env:{ENV}]",
        f"board = {board_id}",
        f"top-module = {top}",
        f"programmer-cmd = {PROGRAMMER_FLASH if flash else PROGRAMMER_SRAM}",
    ]
    if constraints:
        lines.append(f"constraint-file = {CONSTRAINTS_NAME}")
    return "\n".join(lines) + "\n"


def build_staging(
    cfg: ProjectConfig,
    sources: list[Path],
    constraints: Path | None,
    *,
    flash: bool = False,
) -> Staging:
    board_id = resolve_board(cfg.board)
    stage = Staging(dir=staging_dir(cfg.root), keep={CACHE_DIR})
    width = max(3, len(str(len(sources))))
    for index, src in enumerate(sources):
        # The index prefix makes apio's lexicographic order match `sources`; the
        # original name is kept so `*_tb` testbenches are still classified correctly.
        stage.links[f"src/{index:0{width}d}_{src.name}"] = src
    if constraints:
        stage.links[CONSTRAINTS_NAME] = constraints
    stage.files["apio.ini"] = apio_ini(board_id, cfg.top, constraints is not None, flash)
    return stage
