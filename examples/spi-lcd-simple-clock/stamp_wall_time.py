#!/usr/bin/env python3
"""Stamp host wall clock into rtl/wall_time.sv (never commit that file).

Usage:
  python3 stamp_wall_time.py              # stamp only
  python3 stamp_wall_time.py build        # stamp, then shepherd build
  python3 stamp_wall_time.py upload       # stamp, then shepherd upload
  python3 stamp_wall_time.py sim          # stamp, then shepherd sim
"""

from __future__ import annotations

import subprocess
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parent.parent  # examples/ → repo root
OUT = ROOT / "rtl" / "wall_time.sv"


def stamp() -> datetime:
    now = datetime.now()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "\n".join(
            [
                "// Auto-generated by stamp_wall_time.py — do not edit or commit.",
                f"// Stamped at {now.isoformat(timespec='seconds')}",
                f"`define INIT_HOURS   {now.hour}",
                f"`define INIT_MINUTES {now.minute}",
                f"`define INIT_SECONDS {now.second}",
                "",
            ]
        ),
        encoding="utf-8",
    )
    print(f"stamped {now.strftime('%H:%M:%S')} → {OUT.relative_to(ROOT)}", flush=True)
    return now


def main() -> int:
    stamp()
    if len(sys.argv) == 1:
        return 0
    cmd = [
        "uv",
        "run",
        "--directory",
        str(REPO),
        "shepherd",
        "-P",
        str(ROOT),
        *sys.argv[1:],
    ]
    return subprocess.call(cmd)


if __name__ == "__main__":
    raise SystemExit(main())
